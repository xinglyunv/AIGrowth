var defaultIndustry = "其他"

func GenerateQuestions(industry string, brandName string, count int) []string {
	if count <= 0 {
		count = 5
	}

	templates, ok := industryTemplates[industry]
	if !ok {
		templates = industryTemplates[defaultIndustry]
	}

	clampedCount := count
	if clampedCount > len(templates) {
		clampedCount = len(templates)
	}

	indices := rand.Perm(len(templates))[:clampedCount]
	questions := make([]string, clampedCount)
	for i, idx := range indices {
		questions[i] = fmt.Sprintf(templates[idx], brandName)
	}

	return questions
}
